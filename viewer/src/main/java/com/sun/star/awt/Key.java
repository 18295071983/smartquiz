package com.sun.star.awt;

/**
 * Lightweight subset of the UNO com.sun.star.awt.Key constants used by the
 * LibreOffice Android viewer (postKeyEvent key codes). Values match LibreOffice.
 */
public interface Key {
    int BACKSPACE = 1280;
    int UP = 2300;
    int LEFT = 2301;
    int RIGHT = 2303;
    int DOWN = 2304;
    int RETURN = 2307;
}
